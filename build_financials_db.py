"""Load the Layer 1 XBRL statement CSVs into DuckDB.

Paths come from src/dd/config.py, not from this file. Layer 3's structured
retrieval path queries the same tables, so if the two disagreed about where the
warehouse lives, numeric questions would silently read a stale database.
"""

import sys
from pathlib import Path

import duckdb

sys.path.insert(0, str(Path(__file__).parent / "src"))

from dd.config import (  # noqa: E402
    DUCKDB_PATH,
    EVAL_SET_PATH,
    STATEMENTS,
    ensure_dirs,
    get_config,
    statement_csv_path,
)


def build_database() -> None:
    ensure_dirs()
    cfg = get_config()

    if DUCKDB_PATH.exists():
        DUCKDB_PATH.unlink()

    con = duckdb.connect(str(DUCKDB_PATH))
    for table in STATEMENTS:
        csv_path = statement_csv_path(table, cfg)
        if not csv_path.exists():
            raise FileNotFoundError(
                f"missing {csv_path} - run Layer 1 ingestion (document.py) first"
            )
        con.execute(
            f"CREATE TABLE {table} AS SELECT * FROM read_csv_auto(?)",
            [str(csv_path)],
        )
        rows = con.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        print(f"Loaded {table}: {rows} rows  <- {csv_path.relative_to(Path.cwd())}")
    con.close()
    print(f"\nBuilt {DUCKDB_PATH}")


def lookup(label: str, table: str = "income_statement"):
    """Fetch one statement row by its label. Used by Layer 3's numeric path."""
    if table not in STATEMENTS:
        raise KeyError(f"unknown statement {table!r}; expected one of {STATEMENTS}")
    con = duckdb.connect(str(DUCKDB_PATH), read_only=True)
    try:
        return con.execute(f"SELECT * FROM {table} WHERE label = ?", [label]).fetchdf()
    finally:
        con.close()


# The six numeric_lookup answers from eval/eval_set.json, asserted directly
# against the warehouse. If these drift, every numeric eval score is measuring
# a broken loader rather than a broken retriever.
CHECKS = [
    ("income_statement", "Net income", "2025-09-27 (FY)", 112010000000.0),
    ("balance_sheet", "Total assets", "2025-09-27", 359241000000.0),
    ("balance_sheet", "Total liabilities", "2025-09-27", 285508000000.0),
    ("balance_sheet", "Total shareholders’ equity", "2025-09-27", 73733000000.0),
    ("income_statement", "Net sales", "2025-09-27 (FY)", 416161000000.0),
    ("cash_flow", "Cash generated by operating activities", "2025-09-27 (FY)", 111482000000.0),
]


def verify() -> bool:
    con = duckdb.connect(str(DUCKDB_PATH), read_only=True)
    passed = True
    try:
        for table, label, column, expected in CHECKS:
            row = con.execute(
                f'SELECT "{column}" FROM {table} WHERE label = ?', [label]
            ).fetchone()
            actual = row[0] if row else None
            ok = actual == expected
            passed &= ok
            print(f"[{'PASS' if ok else 'FAIL'}] {table}.{label} -> {actual} (want {expected})")
    finally:
        con.close()
    return passed


if __name__ == "__main__":
    build_database()
    print(f"\n--- Verifying against {EVAL_SET_PATH.name} numeric_lookup answers ---")
    if verify():
        print("\nAll checks passed.")
    else:
        print("\nSOME CHECKS FAILED - fix before moving on.")
        sys.exit(1)
