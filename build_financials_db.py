

import duckdb
import os

DB_PATH = "financials.duckdb"
CSV_DIR = os.path.dirname(os.path.abspath(__file__))

TABLES = {
    "income_statement": "apple_income_statement.csv",
    "balance_sheet": "apple_balance_sheet.csv",
    "cash_flow": "apple_cash_flow.csv",
}


def build_database():
    
    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)

    con = duckdb.connect(DB_PATH)

    for table_name, csv_file in TABLES.items():
        csv_path = os.path.join(CSV_DIR, csv_file)
        con.execute(f"""
            CREATE TABLE {table_name} AS
            SELECT * FROM read_csv_auto('{csv_path}')
        """)
        row_count = con.execute(f"SELECT COUNT(*) FROM {table_name}").fetchone()[0]
        print(f"Loaded {table_name}: {row_count} rows")

    con.close()
    print(f"\nBuilt {DB_PATH}")


def lookup(label: str, table: str = "income_statement", db_path: str = DB_PATH):
    
    con = duckdb.connect(db_path, read_only=True)
    result = con.execute(
        f'SELECT * FROM {table} WHERE label = ?', [label]
    ).fetchdf()
    con.close()
    return result


