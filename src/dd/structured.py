"""Layer 3 (structured path): maps a natural-language question to a known
row + year in the DuckDB warehouse, when one applies.

Narrative chunks can't answer "what was net income" precisely - the exact
number lives in a table, not a sentence. This module detects that case and
fetches the number directly, instead of hoping hybrid search stumbles onto
a passage that happens to state it.
"""

from __future__ import annotations

import difflib
import re
from dataclasses import dataclass

import duckdb

from .config import DUCKDB_PATH, Config, get_config

# --- Step 1: curated labels -------------------------------------------------

# A hand-picked subset of the raw CSV labels, not the raw labels themselves.
# The raw tables mix header rows ("Current assets:") with real numeric rows,
# and repeat some labels across segments ("Products" appears once under net
# sales, once under cost of sales). Matching against the raw labels directly
# is ambiguous or outright wrong. Each entry here is the exact label string
# the CSV uses (for the DB lookup) plus a few phrases a question might use.
CANONICAL_LABELS: dict[str, list[tuple[str, list[str]]]] = {
    "income_statement": [
        ("Net sales", ["net sales", "total revenue"]),
        ("Net income", ["net income", "net profit", "earnings", "profit"]),
        ("Gross margin", ["gross margin", "gross profit"]),
        ("Operating income", ["operating income"]),
        ("Research and development", ["research and development", "r&d expense", "r&d"]),
        ("Total operating expenses", ["total operating expenses", "operating expenses"]),
        ("Provision for income taxes", ["income tax", "provision for income taxes", "tax expense"]),
        ("Diluted (in dollars per share)", ["diluted eps", "diluted earnings per share"]),
        ("Basic (in dollars per share)", ["basic eps", "basic earnings per share"]),
        ("iPhone", ["iphone revenue", "iphone"]),
        ("Mac", ["mac revenue", "mac"]),
        ("iPad", ["ipad revenue", "ipad"]),
        ("Wearables, Home and Accessories", ["wearables", "home and accessories"]),
        ("Services", ["services revenue", "services"]),
    ],
    "balance_sheet": [
        ("Total assets", ["total assets"]),
        ("Total liabilities", ["total liabilities"]),
        ("Total current assets", ["total current assets", "current assets"]),
        ("Total current liabilities", ["total current liabilities", "current liabilities"]),
        ("Total shareholders’ equity", ["shareholders equity", "stockholders equity", "total equity"]),
        ("Cash and cash equivalents", ["cash and cash equivalents", "cash on hand"]),
        ("Accounts payable", ["accounts payable"]),
        ("Inventories", ["inventory", "inventories"]),
    ],
    "cash_flow": [
        ("Cash generated by operating activities",
         ["operating cash flow", "cash from operations", "cash generated by operating",
          "operating activities"]),
        ("Cash generated by investing activities",
         ["investing cash flow", "cash from investing", "investing activities"]),
        ("Cash used in financing activities",
         ["financing cash flow", "cash used in financing", "financing activities"]),
        ("Repurchases of common stock",
         ["stock buyback", "share repurchase", "repurchases of common stock"]),
    ],
}

# Some labels are genuinely duplicated in the raw table under different XBRL
# concepts (e.g. "Services" appears once as a revenue line and once as a
# cost-of-sales line - same label text, different meaning). All of this
# module's trigger keywords for such a label ask about the revenue sense,
# never the cost sense, so when a label comes back ambiguous, narrow to the
# row whose `concept` contains this hint before giving up. Verified against
# the real duplicate rows, not guessed - see check_ambiguous.py output.
AMBIGUOUS_LABEL_CONCEPT_HINTS: dict[str, str] = {
    "Services": "RevenueFromContractWithCustomer",
}


def _normalize(text: str) -> str:
    """Lowercase, strip, and fold the filing's smart quote to a plain one -
    the CSV's 'shareholders’ equity' and a user typing "shareholders'
    equity" with an ordinary keyboard apostrophe must compare equal.
    """
    return text.lower().strip().replace("’", "'").replace("‘", "'")


# Matches "2025", "FY2025", "fiscal 2025" -> group 1 is the 4-digit year.
# Matches "FY25", "FY 25" -> group 2 is the 2-digit year, expanded to 20xx.
_YEAR_RE = re.compile(r"\b(?:fy\s?)?(20\d{2})\b|\bfy\s?(\d{2})\b", re.IGNORECASE)


def _extract_year(query: str) -> str | None:
    """Pull a 4-digit fiscal year out of the question, if one was stated.

    Deliberately narrow: only recognizes an explicit year written as 2025,
    FY2025, fiscal 2025, or FY25. A question with no year in it returns
    None - the caller decides what that means (it should not mean "guess
    the most recent year").
    """
    m = _YEAR_RE.search(query)
    if not m:
        return None
    if m.group(1):
        return m.group(1)
    return "20" + m.group(2)


@dataclass
class StructuredMatch:
    table: str
    label: str              # exact label string, used verbatim in the DB query
    matched_via: str        # "keyword" | "fuzzy" - kept for debugging/logging
    year: str | None = None  # 4-digit fiscal year extracted from the question, if any


def match_structured_query(query: str, fuzzy_cutoff: float = 0.72) -> StructuredMatch | None:
    """Try to map a question to one known (table, label) pair, plus a year
    if the question stated one.

    Keyword pass first: cheap, exact, high-confidence. Fuzzy pass only runs
    if keywords found nothing - it catches wording the keyword list didn't
    anticipate, at the cost of being a softer, lower-confidence match.
    """
    q = _normalize(query)
    year = _extract_year(query)

    # Collect every keyword that appears in the question, then keep the
    # LONGEST one, not the first one found. A generic trigger like "revenue"
    # is a substring of almost any revenue-related question, so checking
    # labels in dict order and returning on the first hit means a specific
    # question ("iPhone revenue") can get silently matched to the wrong,
    # more generic label ("Net sales") just because that label happened to
    # be listed first. Longer keyword = more specific = more likely correct.
    keyword_hits: list[tuple[int, str, str]] = []  # (len(kw), table, label)
    for table, entries in CANONICAL_LABELS.items():
        for label, keywords in entries:
            for kw in keywords:
                if kw in q:
                    keyword_hits.append((len(kw), table, label))

    if keyword_hits:
        _, table, label = max(keyword_hits, key=lambda h: h[0])
        return StructuredMatch(table=table, label=label, matched_via="keyword", year=year)

    # Fuzzy fallback: compare against every keyword phrase, not just the
    # canonical label itself - "how much did apple earn" is closer to
    # "earnings" than to the literal string "Net income".
    best: tuple[float, str, str] | None = None  # (score, table, label)
    for table, entries in CANONICAL_LABELS.items():
        for label, keywords in entries:
            for kw in keywords:
                score = difflib.SequenceMatcher(None, q, kw).ratio()
                if best is None or score > best[0]:
                    best = (score, table, label)

    if best and best[0] >= fuzzy_cutoff:
        return StructuredMatch(table=best[1], label=best[2], matched_via="fuzzy", year=year)
    return None


# --- Step 2: fetch the actual number ---------------------------------------

# Column names look like "2025-09-27 (FY)" on income_statement/cash_flow
# (period data - "for the year ended") but just "2025-09-27" on balance_sheet
# (point-in-time data - "as of" one date, no period, hence no "(FY)" tag).
# The suffix is optional here to cover both; this pulls the leading year out
# so it can be compared against the year the question gave.
_COLUMN_YEAR_RE = re.compile(r"^(\d{4})-\d{2}-\d{2}(?:\s\(FY\))?$")


def _year_columns(row: dict) -> dict[str, str]:
    """Map fiscal year -> column name, for every fiscal-year column in a row."""
    out = {}
    for col in row:
        m = _COLUMN_YEAR_RE.match(col)
        if m:
            out[m.group(1)] = col
    return out


def fetch_structured_fact(match: StructuredMatch, cfg: Config | None = None) -> dict | None:
    """Query the DuckDB warehouse for one row, resolve it to one year's
    value, return a plain dict.

    Reads straight from the warehouse file config.py already points at,
    rather than importing build_financials_db.py - that script lives at the
    repo root, outside the installed `dd` package, so importing it from here
    would depend on the caller's working directory instead of being a clean,
    package-internal call.
    """
    _ = cfg or get_config()
    if not DUCKDB_PATH.exists():
        return None

    con = duckdb.connect(str(DUCKDB_PATH), read_only=True)
    try:
        df = con.execute(
            f"SELECT * FROM {match.table} WHERE label = ?", [match.label]
        ).fetchdf()
    finally:
        con.close()

    if df.empty:
        return None
    if len(df) > 1:
        # Known duplicate label (e.g. "Services" as revenue vs. cost-of-sales)?
        # Narrow to the row matching this label's known concept hint before
        # giving up - but only commit to it if that narrows to exactly one row.
        hint = AMBIGUOUS_LABEL_CONCEPT_HINTS.get(match.label)
        if hint is not None:
            narrowed = df[df["concept"].str.contains(hint, na=False)]
            if len(narrowed) == 1:
                df = narrowed

    if len(df) > 1:
        # Still ambiguous - either no hint exists for this label, or the hint
        # didn't narrow it to one row. Surface that rather than silently
        # picking one of several rows.
        return {
            "ambiguous": True,
            "table": match.table,
            "label": match.label,
            "n_rows": len(df),
        }

    row = df.iloc[0].to_dict()
    year_cols = _year_columns(row)

    if match.year is None:
        # The question never said which year. Returning one of several
        # numbers here would be a guess dressed up as an answer - the same
        # reason Layer 4 abstains instead of generating from weak evidence.
        # Say so, and list what years ARE available so the caller (or the
        # user) can ask again with one.
        return {
            "year_unspecified": True,
            "table": match.table,
            "label": match.label,
            "available_years": sorted(year_cols.keys()),
        }

    col = year_cols.get(match.year)
    if col is None:
        return {
            "year_not_found": True,
            "table": match.table,
            "label": match.label,
            "requested_year": match.year,
            "available_years": sorted(year_cols.keys()),
        }

    return {
        "table": match.table,
        "label": match.label,
        "year": match.year,
        "value": row[col],
        "concept": row.get("concept"),
    }


# --- Entry point -------------------------------------------------------


def get_structured_facts(query: str, cfg: Config | None = None) -> list[dict]:
    """Question in, zero or one structured fact out - shaped to drop
    directly into RetrievalOutcome.structured_facts.
    """
    match = match_structured_query(query)
    if match is None:
        return []

    fact = fetch_structured_fact(match, cfg)
    if fact is None:
        return []

    fact["_matched_via"] = match.matched_via
    return [fact]